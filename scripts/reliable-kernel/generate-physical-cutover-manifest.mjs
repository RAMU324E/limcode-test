import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const contractPath = path.join(root, 'docs/architecture/reliable-kernel/contracts/migration.json');
const outputPath = path.join(root, 'backend/reliableKernel/generatedPhysicalCutoverManifest.ts');
const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
const physical = contract.physicalManifest;

if (!physical || !Array.isArray(physical.registeredRoots)) {
  throw new Error('migration.json physicalManifest.registeredRoots 缺失。');
}

const normalizeEntry = (entry) => {
  const relativePath = entry?.pathSource?.relativePath;
  if (typeof entry?.id !== 'string' || typeof relativePath !== 'string' || !isSafeRelativePath(relativePath)) {
    throw new Error(`physical manifest entry无效：${String(entry?.id)}`);
  }
  return {
    id: entry.id,
    relativePath,
    disposition: entry.disposition,
    ...(Array.isArray(entry.preservedScopeKinds) ? { preservedScopeKinds: [...entry.preservedScopeKinds] } : {})
  };
};

const registered = physical.registeredRoots.map(normalizeEntry);
const registeredFiles = physical.registeredFiles.map(normalizeEntry);
const externalWithPaths = physical.externalEntries
  .filter((entry) => typeof entry?.pathSource?.relativePath === 'string')
  .map(normalizeEntry);
const rootPointer = externalWithPaths.find((entry) => entry.id === 'control.root-binding-pointer');
if (!rootPointer) throw new Error('physical manifest缺少control.root-binding-pointer。');

const archiveReset = uniqueEntries([
  ...registered.filter((entry) => entry.disposition === 'archive-reset-whole'),
  ...registeredFiles.filter((entry) => entry.disposition === 'archive-reset-whole'),
  ...externalWithPaths.filter((entry) => entry.disposition === 'archive-reset-whole')
]);
const preserveWhole = uniqueEntries(registered.filter((entry) => entry.disposition === 'preserve-whole'));
const filterByScope = uniqueEntries(registered.filter((entry) => entry.disposition === 'filter-by-scope'));
const externalPreserve = uniqueEntries(externalWithPaths.filter((entry) => entry.disposition === 'preserve-in-place' && entry.id !== rootPointer.id));
const settingsSections = physical.settingsSections
  .filter((entry) => typeof entry?.pathSource?.relativePath === 'string')
  .map((entry) => ({ id: entry.id, relativePath: entry.pathSource.relativePath, disposition: entry.disposition }));
const conversationSettings = {
  filePrefix: 'conversation-',
  fileSuffixes: physical.conversationSettings.sections.map((section) => `-${section}.json`),
  transactionRoot: physical.conversationSettings.transactionRoot.replace(/^settings\//, '')
};

const generated = `/* This file is generated by scripts/reliable-kernel/generate-physical-cutover-manifest.mjs. */

export type PhysicalCutoverDisposition = 'preserve-whole' | 'archive-reset-whole' | 'filter-by-scope' | 'preserve-in-place';

export interface PhysicalCutoverManifestEntry {
  readonly id: string;
  readonly relativePath: string;
  readonly disposition: PhysicalCutoverDisposition;
  readonly preservedScopeKinds?: readonly string[];
}

export interface PhysicalCutoverManifest {
  readonly contractRevision: string;
  readonly preserveWhole: readonly PhysicalCutoverManifestEntry[];
  readonly filterByScope: readonly PhysicalCutoverManifestEntry[];
  readonly archiveReset: readonly PhysicalCutoverManifestEntry[];
  readonly externalPreserve: readonly PhysicalCutoverManifestEntry[];
  readonly settingsSections: readonly PhysicalCutoverManifestEntry[];
  readonly conversationSettings: {
    readonly filePrefix: string;
    readonly fileSuffixes: readonly string[];
    readonly transactionRoot: string;
  };
  readonly rootPointerRelativePath: string;
}

export const PHYSICAL_CUTOVER_MANIFEST: PhysicalCutoverManifest = Object.freeze(${JSON.stringify({
  contractRevision: contract.contractRevision,
  preserveWhole,
  filterByScope,
  archiveReset,
  externalPreserve,
  settingsSections,
  conversationSettings,
  rootPointerRelativePath: rootPointer.relativePath
}, null, 2)} as PhysicalCutoverManifest);
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    console.error('generatedPhysicalCutoverManifest.ts与migration.json不一致；请运行 npm run generate:cutover-manifest。');
    process.exit(1);
  }
  console.log('physical cutover manifest生成物与migration.json一致。');
} else {
  fs.writeFileSync(outputPath, generated, 'utf8');
  console.log(`已生成${path.relative(root, outputPath)}。`);
}

function uniqueEntries(entries) {
  const byPath = new Map();
  for (const entry of entries) {
    const existing = byPath.get(entry.relativePath);
    if (existing && existing.id !== entry.id) {
      throw new Error(`physical manifest重复路径：${entry.relativePath} (${existing.id}, ${entry.id})`);
    }
    byPath.set(entry.relativePath, entry);
  }
  return [...byPath.values()].sort((left, right) => left.relativePath.localeCompare(right.relativePath));
}

function isSafeRelativePath(value) {
  return value.length > 0
    && !path.posix.isAbsolute(value)
    && !value.includes('\\')
    && !value.split('/').some((part) => !part || part === '.' || part === '..');
}
